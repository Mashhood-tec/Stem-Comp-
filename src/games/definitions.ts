const GAME_MAP = new Map(GAMES.map((game) => [game.id, game]));

export function getGame(id: string | undefined | null): GameDefinition | undefined {
  return id ? GAME_MAP.get(id as GameId) : undefined;
}

export function isGameId(value: unknown): value is GameId {
  return typeof value === 'string' && GAME_MAP.has(value as GameId);
}
